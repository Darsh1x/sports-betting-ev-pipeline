CREATE TABLE IF NOT EXISTS BETTING_DB.RAW.ODDS_RAW (
    payload VARIANT,
    source_file STRING,
    file_row_number NUMBER,
    loaded_at TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

CREATE FILE FORMAT IF NOT EXISTS BETTING_DB.RAW.JSON_FF TYPE = JSON;

CREATE STAGE IF NOT EXISTS BETTING_DB.RAW.ODDS_STAGE
    FILE_FORMAT = BETTING_DB.RAW.JSON_FF;
